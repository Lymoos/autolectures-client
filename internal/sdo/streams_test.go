package sdo

import (
	"testing"
	"time"
)

// Реальный набор элементов со страницы курса УИТП: десять потоков разных групп,
// дней и пар. Клиент обязан выбрать ровно свой.
func TestRealStreamList(t *testing.T) {
	items := []WebinarActivity{
		{Title: "УИТП Лекция - вторник, 6 пара - Даева С.Г. - ИВБО-10-23 ИВБО-11-23 ИВБО-12-23 ИВБО-13-23 ИВБО-20-23 ИВБО-21-23 ИВБО-22-23"},
		{Title: "УИТП Лекция - среда, 6 пара - Даева С.Г. - ИКБО-10-23 ИКБО-11-23 ИКБО-12-23 ИКБО-13-23 ИКБО-14-23 ИКБО-15-23"},
		{Title: "УИТП Лекция - пятница, 5 пара - Жигалов К.Ю. - ИНБО-30-23 ИНБО-31-23 ИНБО-32-23"},
		{Title: "УИТП Лекция - пятница, 5 пара - Жигалов К.Ю. - ИНБО-10-23 ИНБО-11-23 ИНБО-12-23 ИНБО-13-23"},
		{Title: "УИТП Лекция - среда, 6 пара - Исаева И.А. - ИКБО-20-23 ИКБО-21-23 ИКБО-22-23 ИКБО-30-23 ИКБО-31-23 ИКБО-32-23"},
		{Title: "УИТП Лекция - среда, 7 пара - Исаева И.А. - ИКБО-40-23 ИКБО-41-23 ИКБО-42-23 ИКБО-43-23"},
		{Title: "УИТП Лекция - среда, 6 пара - Масленников В.В. - ИКБО-50-23 ИКБО-51-23 ИКБО-52-23 ИКБО-60-23 ИКБО-61-23 ИКБО-62-23"},
		{Title: "УИТП Лекция - среда, 7 пара - Масленников В.В. - ИКБО-63-23 ИКБО-64-23 ИКБО-65-23 ИКБО-66-23 ИКБО-67-23"},
		{Title: "УИТП Лекция - четверг, 3 пара - Потапова К.А. - ИКБО-70-23 ИКБО-71-23 ИКБО-72-23 ИКБО-73-23 ИКБО-74-23"},
		{Title: "УИТП Лекция - понедельник, 5 пара - Потапова К.А. - ИНБО-20-23 ИНБО-21-23 ИНБО-22-23 ИМБО-10-23 ИМБО-11-23"},
	}
	// вторник 8 сентября, 6 пара — 18:00
	lesson := time.Date(2026, 9, 8, 18, 0, 0, 0, time.Local)
	got := PickActivities(items, "ИВБО-21-23", "ЛК Управление информационно-технологическими проектами", lesson)
	if len(got) != 1 {
		t.Fatalf("должен остаться один поток, получено %d: %+v", len(got), got)
	}
	if got[0].Title != items[0].Title {
		t.Fatalf("выбран не тот поток: %s", got[0].Title)
	}

	// та же группа, но занятие в среду на 6 паре — нашего потока в списке нет
	wrongDay := time.Date(2026, 9, 9, 18, 0, 0, 0, time.Local)
	if got := PickActivities(items, "ИВБО-21-23", "ЛК УИТП", wrongDay); len(got) != 0 {
		t.Fatalf("в среду у нашей группы потока нет, а выбрано: %+v", got)
	}

	// причина отказа должна быть человеческой
	if r := Reject(items[1], "ИВБО-21-23", lesson); r == "" {
		t.Fatal("чужой поток должен отклоняться с объяснением")
	}
}
